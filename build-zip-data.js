/*
 * Generates zip-data.js from the DoD DTMO ZIP-to-MHA file (sorted_zipmha26.txt).
 *
 * The raw file is ~533 KB over 40,959 "ZIP MHA" lines. Families open this on
 * phones, often on cellular, so the shipped form is packed hard:
 *
 *   1. consecutive ZIPs sharing an MHA collapse into ranges
 *   2. the 339 MHA codes become a dictionary, referenced by index
 *   3. each range is written as base-36 "startDelta.length.mhaIndex", with the
 *      length omitted when it is 1 — the common case
 *
 * Ranges never span a gap in ZIP numbering, so an unassigned ZIP is reported as
 * unknown rather than silently inheriting a neighbour's rate.
 *
 *   node build-zip-data.js <sorted_zipmha26.txt>
 */
'use strict';
const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) { console.error('usage: node build-zip-data.js <sorted_zipmha26.txt>'); process.exit(1); }

const pairs = [];
for (const line of fs.readFileSync(src, 'utf8').split(/\r?\n/)) {
  const m = line.trim().match(/^(\d{5})\s+([A-Z]{2}\d{3})$/);
  if (m) pairs.push([parseInt(m[1], 10), m[2]]);
}
pairs.sort((a, b) => a[0] - b[0]);

const runs = [];                       // {start, end, mha}
for (const [zip, mha] of pairs) {
  const last = runs[runs.length - 1];
  if (last && last.mha === mha && last.end === zip - 1) last.end = zip;
  else runs.push({ start: zip, end: zip, mha });
}

const dict = [...new Set(runs.map(r => r.mha))].sort();
const idx = new Map(dict.map((m, i) => [m, i]));

const b36 = n => n.toString(36);
let prev = 0;
const packed = runs.map(r => {
  const delta = r.start - prev;
  prev = r.start;
  const len = r.end - r.start + 1;
  return b36(delta) + (len > 1 ? '.' + b36(len) : '') + '.' + b36(idx.get(r.mha));
}).join(' ');

const out =
`// Generated by build-zip-data.js from the DoD DTMO ZIP-to-MHA file.
// Do not edit by hand — regenerate when the yearly BAH bundle is updated.
// ${pairs.length} ZIP codes in ${runs.length} ranges over ${dict.length} housing areas.
// ZIP_PACK holds space-separated base-36 records: startDelta[.length].mhaIndex
// (length omitted when 1). Deltas are cumulative from the previous range start.
// Decoded once on load by expandZipRanges() in index.html.
const ZIP_DICT=${JSON.stringify(dict)};
const ZIP_PACK="${packed}";
`;

const dest = path.join(__dirname, 'zip-data.js');
fs.writeFileSync(dest, out);

// Round-trip check: decode exactly as the browser will, compare to source.
const decStart = [], decEnd = [], decMha = [];
let cur = 0;
for (const rec of packed.split(' ')) {
  const p = rec.split('.');
  const delta = parseInt(p[0], 36);
  const len = p.length === 3 ? parseInt(p[1], 36) : 1;
  const mi = parseInt(p[p.length - 1], 36);
  cur += delta;
  decStart.push(cur); decEnd.push(cur + len - 1); decMha.push(dict[mi]);
}
const lookup = z => {
  let lo = 0, hi = decStart.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (z < decStart[mid]) hi = mid - 1;
    else if (z > decEnd[mid]) lo = mid + 1;
    else return decMha[mid];
  }
  return null;
};
let mismatch = 0;
for (const [zip, mha] of pairs) if (lookup(zip) !== mha) mismatch++;
// a ZIP that is not in the source must not resolve to anything
let phantom = 0;
const known = new Set(pairs.map(p => p[0]));
for (let z = 1000; z <= 99999; z += 7) if (!known.has(z) && lookup(z) !== null) phantom++;

console.log('zip rows parsed  :', pairs.length);
console.log('ranges           :', runs.length);
console.log('distinct MHAs    :', dict.length);
console.log('round-trip errors:', mismatch);
console.log('phantom lookups  :', phantom);
console.log('output bytes     :', fs.statSync(dest).size);
